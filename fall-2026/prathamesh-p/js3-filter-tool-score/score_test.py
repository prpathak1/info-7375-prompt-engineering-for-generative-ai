"""One-change-at-a-time score test on the held-out labels (Chapter 9). Offline.

  python -I score_test.py

Each run changes ONE object relative to a named reference and is measured on the 30 held-out postings only
(holdout/LABELS.json). Positive class = label 'fit'. Labels marked 'unsure' are left out of the counts and reported alone.
Two readings of the filter's output:
  "accepted"     = outcome accept
  "reaches me"   = outcome accept or flag (a flag is shown to a human)
Writes out/score_results.json and SCORE-RESULTS.md. No numbers are fitted; nothing is tuned on these labels.
"""
import datetime
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import filter as flt  # noqa: E402
import postings  # noqa: E402

B = flt.JS2_BASELINE
RUNS = [  # (id, description, object changed, reference id, cfg)
    ("C0", "JS2 baseline: inherited rules only (T1-T5, A1-A2, K1)", "-", None, B),
    ("C1", "C0 + seniority gate S1-S5", "filter rule", "C0", B | {"seniority": True}),
    ("C2", "C0 + negation guard A3", "filter rule", "C0", B | {"a3_negation": True}),
    ("C3", "C0 + new title false friends T2a", "filter rule", "C0", B | {"t2a": True}),
    ("C4", "FILTER v0.1 (all approved v0.1 rules)", "filter version", "C0", flt.V01),
    ("C5", "FILTER v0.1 -> v0.2 (EAR exact, A7)", "filter version", "C4", flt.V02),
    ("C6", "v0.2 with K1 threshold 2 -> 3", "setting", "C5", flt.V02 | {"skill_threshold": 3}),
    ("C7", "FILTER v0.2 -> v0.3 (A2 export-license sentence -> A7 flag)", "filter version", "C5", flt.V03),
]


def counts(preds: dict, labels: dict) -> dict:
    c = {"tp": 0, "fp": 0, "fn": 0, "tn": 0}
    for hid, lab in labels.items():
        if lab == "unsure":
            continue
        p, y = preds[hid], lab == "fit"
        c["tp" if p and y else "fp" if p else "fn" if y else "tn"] += 1
    return c


def main() -> int:
    L_ = json.loads((HERE / "holdout" / "LABELS.json").read_text(encoding="utf-8"))
    labels = {r["hid"]: r["label"] for r in L_["labels"]}
    key = {(r["board"], r["id"]): r["hid"] for r in L_["labels"]}
    titles = {r["hid"]: r["title"] for r in L_["labels"]}
    recs = {key[(r["board"], r["id"])]: r for r in postings.load_all() if (r["board"], r["id"]) in key}
    assert len(recs) == 30
    resume = json.loads((HERE / "fixtures" / "resume.fictional.json").read_text(encoding="utf-8"))
    results = {}
    for rid, desc, obj, ref, cfg in RUNS:
        dec = {h: flt.decide(recs[h], resume, cfg) for h in sorted(recs)}
        acc = {h: d["outcome"] == "accept" for h, d in dec.items()}
        reach = {h: d["outcome"] in ("accept", "flag") for h, d in dec.items()}
        results[rid] = {"desc": desc, "object": obj, "ref": ref, "cfg": cfg,
                        "outcomes": {h: f"{d['outcome']} {d['gate'] or ''}".strip() for h, d in dec.items()},
                        "accepted": counts(acc, labels), "reaches_me": counts(reach, labels),
                        "accepted_ids": [h for h in acc if acc[h]], "reach_ids": [h for h in reach if reach[h]]}
    now = datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S %Z")
    (HERE / "out").mkdir(exist_ok=True)
    (HERE / "out" / "score_results.json").write_text(json.dumps({"run": now, "results": results}, indent=1), encoding="utf-8")

    n_fit = sum(v == "fit" for v in labels.values())
    n_nf = sum(v == "not_fit" for v in labels.values())
    M = ["# SCORE-RESULTS (generated by `python -I score_test.py`)", "",
         f"- **Run:** {now}. **Held-out:** 30 postings: {n_fit} fit, {n_nf} not_fit, "
         f"{sum(v == 'unsure' for v in labels.values())} unsure (left out of the counts).",
         "- **Counts, not rates:** with 1 positive label, recall can only be 0/1 or 1/1.", "",
         "| Run | What changed (one object) | Object | vs | accepted: TP / FP / FN / TN | reaches me: TP / FP / FN / TN | accepted | reaches me |",
         "|---|---|---|---|---|---|---|---|"]
    for rid, r in results.items():
        a, m = r["accepted"], r["reaches_me"]
        M.append(f"| {rid} | {r['desc']} | {r['object']} | {r['ref'] or '-'} | {a['tp']} / {a['fp']} / {a['fn']} / {a['tn']} | "
                 f"{m['tp']} / {m['fp']} / {m['fn']} / {m['tn']} | {', '.join(r['accepted_ids']) or '-'} | {', '.join(r['reach_ids']) or '-'} |")
    M += ["", "## What each change moved (held-out postings whose outcome differs from the reference)", ""]
    for rid, r in results.items():
        if not r["ref"]:
            continue
        ref = results[r["ref"]]["outcomes"]
        diff = [h for h in sorted(recs) if r["outcomes"][h] != ref[h]]
        M.append(f"- **{rid} vs {r['ref']}:** " + ("no held-out outcome changed." if not diff else "; ".join(
            f"{h} ({labels[h]}) {titles[h].strip()}: {ref[h]} → {r['outcomes'][h]}" for h in diff)))
    M += ["", "## Every held-out outcome per run", "", "| HID | Label | Title | " + " | ".join(results) + " |",
          "|---|---|---|" + "---|" * len(results)]
    for h in sorted(recs):
        M.append(f"| {h} | {labels[h]} | {titles[h].strip()[:55]} | " + " | ".join(results[r]["outcomes"][h] for r in results) + " |")
    (HERE / "SCORE-RESULTS.md").write_text("\n".join(M) + "\n", encoding="utf-8")
    print(f"[score] {len(results)} runs on 30 held-out postings -> SCORE-RESULTS.md, out/score_results.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
